    gate_configuration = {

        "baseline_accuracy":
            baseline_accuracy,

        "allowed_accuracy_drop":
            allowed_accuracy_drop,

        "minimum_candidate_accuracy":
            minimum_candidate_accuracy,

        "minimum_absolute_improvement": {

            "precision_score":
                0.001,

            "recall_score":
                0.001,

            "f1_score":
                0.001,
        },
    }


    mlflow.log_dict(
        gate_configuration,
        (
            "quality_gate/"
            "gate_configuration.json"
        ),
    )


    # =====================================================
