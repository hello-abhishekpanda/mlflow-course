# 12. CALCULATE PAYFLOW-SPECIFIC METRICS
# =========================================================

def calculate_native_metrics(
    model: Any,
) -> dict[str, float]:
    """
    Calculate PayFlow-specific metrics using the untouched
    holdout test set.

    The MLflow model is a complete sklearn Pipeline:

        raw PayFlow input
               ↓
        preprocessing
               ↓
        classifier

    We explicitly calculate success probabilities so our
    metrics can include:

        ROC-AUC
        Failed PR-AUC
        Failed Precision
        Failed Recall
        Failed F1
        Log Loss
    """

    # -----------------------------------------------------
    # Generate hard predictions.
    # -----------------------------------------------------

    predictions = (
        model.predict(
            X_test
        )
    )


    # -----------------------------------------------------
    # Generate probability matrix.
    # -----------------------------------------------------

    probability_matrix = (
        model.predict_proba(
            X_test
        )
    )


    # -----------------------------------------------------
    # Access fitted classifier.
    # -----------------------------------------------------

    classifier = (
        model
        .named_steps[
            "classifier"
        ]
    )


    classifier_classes = (
        classifier.classes_
    )


    # -----------------------------------------------------
    # We need the probability for SUCCESS=1.
    #
    # Never hard-code [:, 1] without checking the actual
    # class ordering.
    # -----------------------------------------------------

    if 1 not in classifier_classes:

        raise ValueError(
            "Classifier does not contain SUCCESS class 1. "
            f"Classes found: {classifier_classes}"
        )


    success_class_index = (
        list(
            classifier_classes
        )
        .index(1)
    )


    success_probability = (
        probability_matrix[
            :,
            success_class_index,
        ]
    )


    metrics = (
        calculate_payment_metrics(

            y_true=(
                y_test
            ),

            y_pred=(
                predictions
            ),

            success_probability=(
                success_probability
            ),
        )
    )


    # -----------------------------------------------------
    # Convert NumPy numeric scalar values to Python float.
    # This keeps MLflow/JSON serialization predictable.
    # -----------------------------------------------------

    return {

        metric_name:
            float(metric_value)

        for (
            metric_name,
            metric_value,
        )
        in metrics.items()
    }


